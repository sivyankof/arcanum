/** DEV-подмена «сейчас» для окна лунного расклада (спека 51, лайв-проверка).
 *  Окно живёт трое суток из ~15, и на лайв-проверке открытое состояние иначе не увидеть —
 *  прецедент DEV-строки «Пропустить вчера» (задача 10). Подменяется ВРЕМЯ, а не результат
 *  проверки: тогда панель на луне, карточка в списке, гейт маршрута и оверлайн расклада
 *  согласованы между собой ровно так, как будут в день события. Вне __DEV__ и при выключенном
 *  тумблере — null, и все потребители берут настоящее время. */
import { useMemo } from 'react';
import { useApp } from '../store/useApp';
import { nearestMoonEvent } from './moonSpread';

export function useDevMoonNow(): Date | null {
  const on = useApp((s) => s.devMoonOpen);
  // момент ближайшего события — он же «сейчас»; день считать заново незачем, пока тумблер включён
  return useMemo(() => (__DEV__ && on ? nearestMoonEvent()?.at ?? null : null), [on]);
}
